import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { sourceFiles, workspacePackages } from './workspace.mjs';
import { sourceDigest } from './source-digest.mjs';
/** Require generated JS exclusions to carry an integrity receipt, with source-map provenance. */
export function outputIntegrity({ root = process.cwd() } = {}) {
 const files = sourceFiles({ root, includeOutput: true }).filter(file => file.split('/').some(part => ['dist','coverage'].includes(part)));
 return files.flatMap(file => verifyOutput({ file, root }));
}
/** Receipts are generated by the build wrapper, never supplied as source exclusions. */
function verifyOutput({ file, root }) {
 const path = resolve(root, file); const receiptPath = resolve(dirname(path), '.om-generated.json');
 if (!existsSync(receiptPath)) return [`${file}: missing generated integrity receipt`];
 const receipt = JSON.parse(readFileSync(receiptPath, 'utf8'));
 const digest = createHash('sha256').update(readFileSync(path)).digest('hex');
 if (receipt.outputs[file] !== digest) return [`${file}: generated output checksum mismatch`];
 if (!receipt.sourceDigest || receipt.toolchain !== 'Node24.2.0-pnpm10.24.0') return [`${file}: missing generated provenance`];
 const owner = workspacePackages({ root }).find(pkg => pkg.name === receipt.owner && ['dist','coverage'].some(folder => file.startsWith(pkg.path + '/' + folder + '/')));
 if (!owner || sourceDigest({ root, owner }) !== receipt.sourceDigest) return [`${file}: stale or invalid generated source provenance`];
 return [];
}
